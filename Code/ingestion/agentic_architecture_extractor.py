# BASE EXTRACTION AGENT
# ============================================================

class ExtractionAgent:
    """
    Base class for specialized AUTOSAR extraction agents.
    """

    def __init__(
        self,
        name: str,
        entity_type: str,
        instructions: str
    ):

        self.name = name

        self.entity_type = entity_type

        self.instructions = instructions

    def build_prompt(
        self,
        page_context: str
    ) -> str:

        return f"""
You are the {self.name} in a specialized
AUTOSAR architecture analysis system.

Your ONLY task is:

{self.entity_type}

You are one specialized agent in a multi-agent system.

Do NOT perform the tasks of other agents.

============================================================
GENERAL RULES
============================================================

1. Extract ONLY information explicitly supported by
   the supplied document.

2. Do NOT invent entities.

3. Do NOT use outside AUTOSAR knowledge to create
   missing names.

4. Preserve technical names exactly as they appear.

5. Every extracted entity must contain evidence.

6. Every extracted entity must contain its source page.

7. If no valid entity exists, return:

{{
    "entities": []
}}

8. Ignore ordinary English words.

9. Do not turn descriptive phrases into entity names.

10. Do not extract an entity simply because a keyword
    appears nearby.

11. Avoid duplicate entities within the same page.

12. Return JSON ONLY.

============================================================
SPECIALIZED AGENT RULES
============================================================

{self.instructions}

============================================================
OUTPUT FORMAT
============================================================

Return:

{{
    "entities": [
        {{
            "name": "exact technical name",
            "type": "{self.entity_type}",
            "page": 0,
            "section": "section name",
            "evidence": "short supporting evidence"
        }}
    ]
}}

============================================================
DOCUMENT CONTEXT
============================================================

{page_context}
"""

    def extract_from_batch(
        self,
        batch: List[Dict[str, Any]]
    ) -> List[Dict[str, Any]]:

        page_context = format_pages(
            batch
        )

        prompt = self.build_prompt(
            page_context
        )

        try:

            response = call_ollama(
                prompt
            )

            result = extract_json(
                response
            )

            entities = result.get(
                "entities",
                []
            )

            if not isinstance(
                entities,
                list
            ):

                return []

            return self.validate_results(
                entities,
                batch
            )

        except Exception as exc:

            print(
                f"    [{self.name}] "
                f"Batch failed: {exc}"
            )

            return []

    @staticmethod
    def validate_results(
        entities: List[Dict[str, Any]],
        batch: List[Dict[str, Any]]
    ) -> List[Dict[str, Any]]:

        valid_pages = set()

        for page in batch:

            valid_pages.add(
                str(
                    page.get(
                        "page_number"
                    )
                )
            )

        validated = []

        for item in entities:

            if not isinstance(
                item,
                dict
            ):

                continue

            name = str(
                item.get(
                    "name",
                    ""
                )
            ).strip()

            if not name:
                continue

            page = item.get(
                "page"
            )

            # Keep only pages actually supplied to the agent.
            if page is not None:

                if str(page) not in valid_pages:

                    continue

            evidence = str(
                item.get(
                    "evidence",
                    ""
                )
            ).strip()

            if not evidence:
                continue

            item["name"] = name

            item["evidence"] = evidence

            validated.append(
                item
            )

        return validated


