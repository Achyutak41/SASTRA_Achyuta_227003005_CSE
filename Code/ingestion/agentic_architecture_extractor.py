class ArchitectureAgentManager:
    """
    Coordinates the specialized extraction agents.
    """

    AGENT_TYPES = {

        "AUTOSAR Component Extraction Agent":
            "component",

        "AUTOSAR Interface Extraction Agent":
            "interface",

        "AUTOSAR Port Extraction Agent":
            "port",

        "AUTOSAR Signal Extraction Agent":
            "signal",

        "AUTOSAR Runnable Extraction Agent":
            "runnable",

        "AUTOSAR Relationship Extraction Agent":
            "relationship"
    }

    RESULT_KEYS = {

        "component":
            "components",

        "interface":
            "interfaces",

        "port":
            "ports",

        "signal":
            "signals",

        "runnable":
            "runnables",

        "relationship":
            "relationships"
    }

    def __init__(self):

        self.agents = [

            ComponentAgent(),

            InterfaceAgent(),

            PortAgent(),

            SignalAgent(),

            RunnableAgent(),

            RelationshipAgent()
        ]

    def run(
        self,
        pages: List[Dict[str, Any]]
    ) -> Dict[str, Any]:

        final_result = {

            "components": [],

            "interfaces": [],

            "ports": [],

            "signals": [],

            "runnables": [],

            "relationships": []
        }

        print()
        print(
            "=" * 70
        )

        print(
            "AUTOSAR MULTI-AGENT ARCHITECTURE EXTRACTION"
        )

        print(
            "=" * 70
        )

        print(
            f"Total document pages : {len(pages)}"
        )

        print(
            f"Specialized agents   : {len(self.agents)}"
        )

        print(
            f"Pages per batch      : {PAGES_PER_BATCH}"
        )

        print(
            f"Max batch context    : {MAX_BATCH_CHARS}"
        )

        print(
            "=" * 70
        )

        # ----------------------------------------------------
        # RUN EACH SPECIALIZED AGENT
        # ----------------------------------------------------

        for agent in self.agents:

            agent_name = agent.name

            agent_type = self.AGENT_TYPES[
                agent_name
            ]

            result_key = self.RESULT_KEYS[
                agent_type
            ]

            print()
            print(
                "-" * 70
            )

            print(
                f"[AGENT] {agent_name}"
            )

            # ------------------------------------------------
            # ROUTE RELEVANT PAGES
            # ------------------------------------------------

            selected_pages = (
                AgentPageRouter.route(
                    pages,
                    agent_type
                )
            )

            print(
                f"  Relevant pages: "
                f"{len(selected_pages)} / "
                f"{len(pages)}"
            )

            if not selected_pages:

                print(
                    "  No relevant pages found."
                )

                continue

            # ------------------------------------------------
            # CREATE BATCHES
            # ------------------------------------------------

            batches = create_page_batches(
                selected_pages
            )

            print(
                f"  Batches: {len(batches)}"
            )

            agent_results = []

            # ------------------------------------------------
            # PROCESS BATCHES
            # ------------------------------------------------

            for batch_number, batch in enumerate(
                batches,
                start=1
            ):

                page_numbers = [

                    str(
                        page.get(
                            "page_number",
                            "?"
                        )
                    )

                    for page in batch
                ]

                print(
                    f"  Batch "
                    f"{batch_number}/"
                    f"{len(batches)} "
                    f"pages={page_numbers}"
                )

                results = (
                    agent.extract_from_batch(
                        batch
                    )
                )

                agent_results.extend(
                    results
                )

            # ------------------------------------------------
            # DEDUPLICATE
            # ------------------------------------------------

            if agent_type == "relationship":

                cleaned = (
                    self.deduplicate_relationships(
                        agent_results
                    )
                )

            else:

                cleaned = (
                    self.deduplicate_entities(
                        agent_results
                    )
                )

            final_result[
                result_key
            ] = cleaned

            print(
                f"  Final extracted: "
                f"{len(cleaned)}"
            )

        return final_result

    # ========================================================
    # ENTITY DEDUPLICATION
    # ========================================================

    @staticmethod
    def deduplicate_entities(
        items: List[Dict[str, Any]]
    ) -> List[Dict[str, Any]]:

        unique = {}

        for item in items:

            if not isinstance(
                item,
                dict
            ):

                continue

            name = str(
                item.get(
                    "name",
                    ""
                )
            ).strip()

            if not name:

                continue

            # Same entity on different pages should be
            # consolidated by name.
            key = name.lower()

            if key not in unique:

                unique[key] = {

                    "name": name,

                    "type": item.get(
                        "type",
                        ""
                    ),

                    "page": item.get(
                        "page"
                    ),

                    "section": item.get(
                        "section",
                        ""
                    ),

                    "evidence": item.get(
                        "evidence",
                        ""
                    ),

                    "evidence_locations": []
                }

            page = item.get(
                "page"
            )

            evidence = item.get(
                "evidence",
                ""
            )

            location = {

                "page": page,

                "section": item.get(
                    "section",
                    ""
                ),

                "evidence": evidence
            }

            existing_locations = unique[
                key
            ][
                "evidence_locations"
            ]

            # Avoid duplicate evidence locations.
            already_exists = any(

                loc.get("page") == page
                and
                loc.get("evidence") == evidence

                for loc in existing_locations
            )

            if not already_exists:

                existing_locations.append(
                    location
                )

        return list(
            unique.values()
        )

    # ========================================================
    # RELATIONSHIP DEDUPLICATION
    # ========================================================

    @staticmethod
    def deduplicate_relationships(
        items: List[Dict[str, Any]]
    ) -> List[Dict[str, Any]]:

        unique = {}

        for item in items:

            if not isinstance(
                item,
                dict
            ):

                continue

            source = str(
                item.get(
                    "source",
                    ""
                )
            ).strip()

            relation = str(
                item.get(
                    "relation",
                    ""
                )
            ).strip()

            target = str(
                item.get(
                    "target",
                    ""
                )
            ).strip()

            if not source:
                continue

            if not relation:
                continue

            if not target:
                continue

            key = (

                source.lower(),

                relation.lower(),

                target.lower()
            )

            if key not in unique:

                unique[key] = {

                    "source": source,

                    "relation": relation,

                    "target": target,

                    "page": item.get(
                        "page"
                    ),

                    "section": item.get(
                        "section",
                        ""
                    ),

                    "evidence": item.get(
                        "evidence",
                        ""
                    ),

                    "evidence_locations": []
                }

            location = {

                "page": item.get(
                    "page"
                ),

                "section": item.get(
                    "section",
                    ""
                ),

                "evidence": item.get(
                    "evidence",
                    ""
                )
            }

            existing = unique[
                key
            ][
                "evidence_locations"
            ]

            already_exists = any(

                loc.get("page")
                ==
                location.get("page")

                and

                loc.get("evidence")
                ==
                location.get("evidence")

                for loc in existing
            )

            if not already_exists:

                existing.append(
                    location
                )

        return list(
            unique.values()
        )


