class AgentPageRouter:
    """
    Routes only relevant PDF pages to each specialized agent.

    This is the main improvement over the previous design.

    Instead of:

        171 pages × 6 agents

    we do:

        relevant pages → relevant agent
    """

    KEYWORDS = {

        "component": [

            "software component",

            "software components",

            "sw-c",

            "swc",

            "basic software",

            "bsw",

            "bsw module",

            "software module",

            "component",

            "rte",

            "runtime environment",

            "application layer",

            "service layer",

            "ecu abstraction"
        ],

        "interface": [

            "interface",

            "interfaces",

            "portinterface",

            "port interface",

            "senderreceiverinterface",

            "sender-receiver interface",

            "clientserverinterface",

            "client-server interface",

            "s/r interface",

            "service interface",

            "client/server interface"
        ],

        "port": [

            "p-port",

            "r-port",

            "pport",

            "rport",

            "provided port",

            "required port",

            "port prototype",

            "provide port",

            "require port"
        ],

        "signal": [

            "signal",

            "signals",

            "i-signal",

            "i-signal-group",

            "signal group",

            "i-pdu",

            "i-pdus",

            "pdu",
            
            "pdus"
        ],

        "runnable": [

            "runnable",

            "runnables",

            "runnableentity",

            "runnable entity",

            "runnable entities"
        ],

        "relationship": [

            "provides",

            "provided",

            "requires",

            "required",

            "uses",

            "communicates",

            "communication",

            "depends on",

            "dependent",

            "connected to",

            "connects",

            "interaction",

            "interacts",

            "relationship",

            "relations",
            
            "mapping",

            "mapped to"
        ]
    }

    @classmethod
    def route(
        cls,
        pages: List[Dict[str, Any]],
        agent_type: str
    ) -> List[Dict[str, Any]]:
        """
        Select pages relevant to a particular agent.
        """

        keywords = cls.KEYWORDS.get(
            agent_type,
            []
        )

        selected_pages = []

        for page in pages:

            text = clean_text(
                page.get(
                    "text",
                    ""
                )
            ).lower()

            if not text:
                continue

            matched = False

            for keyword in keywords:

                if keyword in text:

                    matched = True

                    break

            if matched:

                selected_pages.append(
                    page
                )

        return selected_pages


# ============================================================
# PAGE BATCHING
# ============================================================

def create_page_batches(
    pages: List[Dict[str, Any]]
) -> List[List[Dict[str, Any]]]:
    """
    Split selected pages into small batches.
    """

    batches = []

    current_batch = []

    current_chars = 0

    for page in pages:

        page_text = truncate_text(
            page.get(
                "text",
                ""
            )
        )

        estimated_size = len(
            page_text
        )

        # Start a new batch when the current batch is full.
        if (
            current_batch
            and
            (
                len(current_batch)
                >= PAGES_PER_BATCH
                or
                current_chars + estimated_size
                > MAX_BATCH_CHARS
            )
        ):

            batches.append(
                current_batch
            )

            current_batch = []

            current_chars = 0

        current_batch.append(
            page
        )

        current_chars += estimated_size

    if current_batch:

        batches.append(
            current_batch
        )

    return batches


# ============================================================
# PAGE FORMATTER
# ============================================================

def format_pages(
    batch: List[Dict[str, Any]]
) -> str:
    """
    Convert PDF pages into structured LLM context.
    """

    output = []

    for page in batch:

        page_number = page.get(
            "page_number",
            "unknown"
        )

        section = page.get(
            "section",
            ""
        )

        text = truncate_text(
            page.get(
                "text",
                ""
            )
        )

        output.append(

            f"""
--- PAGE {page_number} ---

SECTION:
{section}

TEXT:
{text}
"""
        )

    return "\n".join(
        output
    )


