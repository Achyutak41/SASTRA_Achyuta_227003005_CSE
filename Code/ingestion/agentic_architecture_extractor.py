# ============================================================
# CONFIGURATION
# ============================================================

OLLAMA_URL = "http://localhost:11434/api/generate"

MODEL_NAME = "mistral"

BASE_DIR = Path(__file__).resolve().parents[2]

PROCESSED_DIR = BASE_DIR / "Input_Data" / "processed"

OUTPUT_DIR = BASE_DIR / "Input_Data" / "processed"

# Keep batches small because local Ollama/Mistral can become
# very slow with large PDF contexts.
PAGES_PER_BATCH = 2

# Maximum amount of text sent from one page.
MAX_PAGE_CHARS = 7000

# Maximum approximate context sent to one LLM call.
MAX_BATCH_CHARS = 12000

# Ollama timeout.
OLLAMA_TIMEOUT = 300

# Retry count for temporary Ollama failures.
OLLAMA_RETRIES = 1


# ============================================================
# COMMON UTILITIES
# ============================================================

def clean_text(text: str) -> str:
    """
    Clean PDF extracted text while preserving technical terms.
    """

    if not text:
        return ""

    text = text.replace("\x00", " ")

    text = re.sub(
        r"\s+",
        " ",
        text
    )

    return text.strip()


def truncate_text(
    text: str,
    max_chars: int = MAX_PAGE_CHARS
) -> str:
    """
    Prevent extremely large PDF pages from creating
    unnecessarily large LLM prompts.
    """

    text = clean_text(text)

    if len(text) <= max_chars:
        return text

    return text[:max_chars] + " ..."


def load_processed_document(
    json_path: str
) -> Dict[str, Any]:
    """
    Load the processed PDF JSON generated by the
    PDF ingestion checkpoint.
    """

    path = Path(json_path)

    if not path.exists():
        raise FileNotFoundError(
            f"Processed JSON not found: {json_path}"
        )

    with open(
        path,
        "r",
        encoding="utf-8"
    ) as f:

        return json.load(f)


def save_json(
    data: Dict[str, Any],
    output_path: str
):
    """
    Save architecture extraction result.
    """

    output_path = Path(output_path)

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True
    )

    with open(
        output_path,
        "w",
        encoding="utf-8"
    ) as f:

        json.dump(
            data,
            f,
            indent=2,
            ensure_ascii=False
        )


# ============================================================
# OLLAMA
# ============================================================

def call_ollama(
    prompt: str
) -> str:
    """
    Send a prompt to the local Ollama Mistral model.

    JSON mode is used to reduce malformed responses.
    """

    payload = {

        "model": MODEL_NAME,

        "prompt": prompt,

        "stream": False,

        "format": "json",

        "options": {

            "temperature": 0,

            # Limit generation length.
            "num_predict": 700,

            # Keep model context manageable.
            "num_ctx": 4096
        }
    }

    last_error = None

    for attempt in range(
        OLLAMA_RETRIES + 1
    ):

        try:

            response = requests.post(
                OLLAMA_URL,
                json=payload,
                timeout=OLLAMA_TIMEOUT
            )

            response.raise_for_status()

            result = response.json()

            return result.get(
                "response",
                ""
            )

        except (
            requests.exceptions.Timeout,
            requests.exceptions.ConnectionError
        ) as exc:

            last_error = exc

            print(
                f"    Ollama attempt "
                f"{attempt + 1}/"
                f"{OLLAMA_RETRIES + 1} failed: "
                f"{exc}"
            )

            if attempt < OLLAMA_RETRIES:

                print(
                    "    Retrying..."
                )

                time.sleep(2)

    raise RuntimeError(
        f"Ollama request failed after "
        f"{OLLAMA_RETRIES + 1} attempts: "
        f"{last_error}"
    )


# ============================================================
# JSON PARSER
# ============================================================

def extract_json(
    response: str
) -> Dict[str, Any]:
    """
    Convert the LLM response into a Python dictionary.
    """

    if not response:
        raise ValueError(
            "Empty response received from Ollama."
        )

    response = response.strip()

    # Remove markdown fences if present.
    response = re.sub(
        r"```json\s*",
        "",
        response,
        flags=re.IGNORECASE
    )

    response = re.sub(
        r"```\s*",
        "",
        response
    )

    # Find JSON object.
    start = response.find("{")

    end = response.rfind("}")

    if start == -1 or end == -1:

        raise ValueError(
            "No JSON object found in Ollama response."
        )

    json_text = response[
        start:end + 1
    ]

    try:

        result = json.loads(
            json_text
        )

    except json.JSONDecodeError as exc:

        raise ValueError(
            f"Invalid JSON returned by Ollama: {exc}"
        )

    if not isinstance(
        result,
        dict
    ):

        raise ValueError(
            "Ollama JSON response is not an object."
        )

    return result


